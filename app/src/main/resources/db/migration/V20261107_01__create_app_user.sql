-- ============================================================
-- BYOK 阶段一：用户体系
-- 说明：本迁移只做增量建表，不删除、不修改任何既有业务数据。
-- ============================================================

CREATE TABLE app_user (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      VARCHAR(64)  NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  email         VARCHAR(128),
  role          VARCHAR(20)  NOT NULL DEFAULT 'USER',
  status        VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
  created_at    TIMESTAMP(6) NOT NULL,
  updated_at    TIMESTAMP(6) NOT NULL,
  last_login_at TIMESTAMP(6),
  CONSTRAINT uk_app_user_username UNIQUE (username),
  CONSTRAINT uk_app_user_email UNIQUE (email),
  CONSTRAINT ck_app_user_role CHECK (role IN ('USER', 'ADMIN')),
  CONSTRAINT ck_app_user_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

COMMENT ON TABLE app_user IS '平台用户（BYOK 阶段一）';
COMMENT ON COLUMN app_user.password_hash IS 'BCrypt 哈希；不存在明文密码';
COMMENT ON COLUMN app_user.role IS 'USER / ADMIN；注册接口只能产生 USER';
