-- ============================================================
-- 简历管理模块升级：在线结构化简历文档
--
-- 设计要点：
-- 1. 与原始上传简历（resumes）完全解耦：在线编辑内容独立保存，
--    source_resume_id 仅作关联，原始文件与 AI 分析结果一律不动。
-- 2. content 沿用本项目既有 JSON 文本约定（TEXT + ObjectMapper 手工序列化），
--    与 resume_analyses.strengths_json 一致，保证 ddl-auto=validate 与 H2 测试兼容。
-- 3. version 作为 @Version 乐观锁字段，避免旧数据覆盖新数据。
-- 4. 所有查询必须带 user_id；联合唯一约束保证一份原始简历只初始化一个在线版本。
-- 5. 原始简历被删除时置空关联，不连带删除用户已编辑的成果，
--    因此无需改动 ResumeDeleteService。
-- ============================================================

CREATE TABLE IF NOT EXISTS resume_documents (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          BIGINT        NOT NULL,
  title            VARCHAR(200)  NOT NULL,
  source_resume_id BIGINT,
  content          TEXT          NOT NULL,
  template_code    VARCHAR(64)   NOT NULL DEFAULT 'default',
  version          BIGINT        NOT NULL DEFAULT 0,
  created_at       TIMESTAMP(6)  NOT NULL,
  updated_at       TIMESTAMP(6)  NOT NULL,
  CONSTRAINT fk_resume_documents_user
    FOREIGN KEY (user_id) REFERENCES app_user(id),
  CONSTRAINT fk_resume_documents_source
    FOREIGN KEY (source_resume_id) REFERENCES resumes(id) ON DELETE SET NULL,
  CONSTRAINT uk_resume_documents_user_source UNIQUE (user_id, source_resume_id)
);

CREATE INDEX IF NOT EXISTS idx_resume_documents_user
  ON resume_documents (user_id);
CREATE INDEX IF NOT EXISTS idx_resume_documents_user_updated
  ON resume_documents (user_id, updated_at DESC);

COMMENT ON TABLE resume_documents IS '在线结构化简历文档（与原始上传简历分离）';
COMMENT ON COLUMN resume_documents.user_id IS '归属用户，所有读写必须以此隔离';
COMMENT ON COLUMN resume_documents.source_resume_id IS '关联原始上传简历，可为空表示空白简历';
COMMENT ON COLUMN resume_documents.content IS '结构化简历 JSON 文本（basicInfo/education/projects/skills/internships/awards）';
COMMENT ON COLUMN resume_documents.template_code IS '简历模板编码，第一版仅 default';
COMMENT ON COLUMN resume_documents.version IS '乐观锁版本，每次确认修改或保存递增';
