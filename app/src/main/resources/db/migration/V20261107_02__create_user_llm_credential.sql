-- ============================================================
-- BYOK 阶段一：用户级 LLM 凭证
-- 安全约定：
--   1. 只存 AES-256-GCM 密文与 nonce，绝不存明文 API Key。
--   2. key_tail 仅保存明文末尾 4 位，用于前端脱敏展示。
--   3. 不存 base_url：地址一律由服务端白名单解析，规避 SSRF。
-- ============================================================

CREATE TABLE user_llm_credential (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id            BIGINT       NOT NULL,
  provider_key       VARCHAR(64)  NOT NULL,
  model_name         VARCHAR(128) NOT NULL,
  api_key_ciphertext VARCHAR(4096) NOT NULL,
  api_key_nonce      VARCHAR(64)  NOT NULL,
  key_version        SMALLINT     NOT NULL DEFAULT 1,
  credential_version BIGINT       NOT NULL DEFAULT 1,
  key_tail           VARCHAR(8),
  status             VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
  created_at         TIMESTAMP(6) NOT NULL,
  updated_at         TIMESTAMP(6) NOT NULL,
  CONSTRAINT fk_user_llm_credential_user
    FOREIGN KEY (user_id) REFERENCES app_user(id) ON DELETE CASCADE,
  CONSTRAINT uk_user_llm_credential_user_provider UNIQUE (user_id, provider_key),
  CONSTRAINT ck_user_llm_credential_status
    CHECK (status IN ('ACTIVE', 'INVALID', 'DISABLED'))
);

CREATE INDEX idx_user_llm_credential_user ON user_llm_credential (user_id);
CREATE INDEX idx_user_llm_credential_keyver ON user_llm_credential (key_version);

COMMENT ON TABLE user_llm_credential IS '用户自带 LLM 凭证（密文存储）';
COMMENT ON COLUMN user_llm_credential.api_key_ciphertext IS 'Base64(AES-256-GCM 密文，含 16 字节认证标签)';
COMMENT ON COLUMN user_llm_credential.api_key_nonce IS 'Base64(12 字节随机 nonce)，每次加密重新生成';
COMMENT ON COLUMN user_llm_credential.key_version IS '加密主密钥版本，为将来轮换预留';
COMMENT ON COLUMN user_llm_credential.credential_version IS '用户凭证配置版本，每次写操作递增';
COMMENT ON COLUMN user_llm_credential.key_tail IS '明文末尾 4 位，仅用于脱敏展示';
